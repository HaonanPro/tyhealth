const langToggle = document.querySelector("[data-lang-toggle]");
const i18nNodes = document.querySelectorAll("[data-i18n]");

function applyLanguage(lang) {
  const language = translations[lang] ? lang : "zh";
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.body.dataset.lang = language;
  i18nNodes.forEach((node) => {
    const key = node.dataset.i18n;
    const val = translations[language][key];
    if (val !== undefined) node.textContent = val;
  });
  if (langToggle) langToggle.textContent = language === "zh" ? "EN" : "中";
}

// ── IP-based auto language detection ──
const params = new URLSearchParams(window.location.search);

// Priority: URL param > localStorage manual choice > IP detection > fallback zh
function initLanguage() {
  const urlLang = params.get("lang");
  if (urlLang) {
    applyLanguage(urlLang);
    return;
  }

  const stored = localStorage.getItem("ty-lang");
  if (stored) {
    applyLanguage(stored);
    return;
  }

  // IP-based detection
  fetch("https://ipapi.co/json/")
    .then(res => res.json())
    .then(data => {
      const lang = data.country_code === "CN" ? "zh" : "en";
      applyLanguage(lang);
    })
    .catch(() => {
      // fallback to browser language
      const browserLang = navigator.language || navigator.languages[0];
      applyLanguage(browserLang.startsWith("zh") ? "zh" : "en");
    });
}

initLanguage();

if (langToggle) {
  langToggle.addEventListener("click", () => {
    const next = document.body.dataset.lang === "zh" ? "en" : "zh";
    localStorage.setItem("ty-lang", next); // remember user choice
    applyLanguage(next);
  });
}

// ── Hero Carousel ──
(function () {
  const slides = document.querySelectorAll(".hero-slide");
  const dots = document.querySelectorAll(".hero-dot");
  if (slides.length < 2) return;

  let current = 0;
  let timer = null;
  const INTERVAL = 5000;

  function goTo(index) {
    if (index === current) return;
    slides[current].classList.remove("active");
    dots[current].classList.remove("active");
    current = index;
    slides[current].classList.add("active");
    dots[current].classList.add("active");
  }

  function next() {
    goTo((current + 1) % slides.length);
  }

  function startTimer() {
    stopTimer();
    timer = setInterval(next, INTERVAL);
  }

  function stopTimer() {
    if (timer) { clearInterval(timer); timer = null; }
  }

  dots.forEach(function (dot) {
    dot.addEventListener("click", function () {
      goTo(parseInt(this.dataset.index, 10));
      startTimer(); // reset timer after manual click
    });
  });

  // Touch swipe support
  let touchStartX = 0;
  let touchEndX = 0;
  const hero = document.querySelector(".hero");
  if (hero) {
    hero.addEventListener("touchstart", function (e) {
      touchStartX = e.changedTouches[0].screenX;
      stopTimer();
    }, { passive: true });
    hero.addEventListener("touchend", function (e) {
      touchEndX = e.changedTouches[0].screenX;
      const diff = touchStartX - touchEndX;
      if (Math.abs(diff) > 50) {
        if (diff > 0) {
          goTo((current + 1) % slides.length);
        } else {
          goTo((current - 1 + slides.length) % slides.length);
        }
      }
      startTimer();
    });
    hero.addEventListener("mouseenter", stopTimer);
    hero.addEventListener("mouseleave", startTimer);
  }

  startTimer();
})();
